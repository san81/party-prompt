// Generates public/rapid/items.js from the image folders under public/rapid/items/.
// Run: node scripts/gen-rapid-items.mjs
//
// Most categories map 1:1 to a folder; the answer is the cleaned file name. Two special
// categories SHARE the `letters/` images (single A–X letter pictures):
//   - alphabet      → say the letter shown (answer = the letter)
//   - priorAlphabet → say the letter that comes BEFORE the one shown (answer = prior letter)
// Both are matched locally (single letters), so Jev isn't involved.
import fs from 'node:fs';

const DIR = 'public/rapid/items';
const EXCLUDE = new Set(['missingPerson', 'letters']);   // letters handled specially below

const LABELS = {
  animals:       { en: 'Animals',       te: 'జంతువులు' },
  kitchenObject: { en: 'Kitchen',       te: 'వంటగది వస్తువులు' },
  logo:          { en: 'Brand Logos',   te: 'బ్రాండ్ లోగోలు' },
  moviesNameFromPoster: { en: 'Movie Posters', te: 'సినిమా పోస్టర్లు' },
  seeds:         { en: 'Seeds',         te: 'విత్తనాలు' },
  usStates:      { en: 'US States',     te: 'అమెరికా రాష్ట్రాలు' },
  techIcons:     { en: 'Tech Icons',    te: 'టెక్ ఐకాన్లు' },
  hollywood:     { en: 'Hollywood',     te: 'హాలీవుడ్' },
  scientists:    { en: 'Scientists',    te: 'శాస్త్రవేత్తలు' },
  teluguCinema:  { en: 'Telugu Cinema', te: 'తెలుగు సినిమా' },
  alphabet:      { en: 'Alphabet',      te: 'అక్షరమాల' },
  priorAlphabet: { en: 'Prior Alphabet', te: 'ముందు అక్షరం' },
};

const clean = (f) => {
  let n = f.replace(/\.[^.]+$/, '').replace(/[_-]+/g, ' ').replace(/([a-z0-9])([A-Z])/g, '$1 $2').trim();
  return n.length <= 2 ? n.toUpperCase() : n[0].toUpperCase() + n.slice(1);
};
const imgs = (dir) => fs.readdirSync(dir).filter((f) => /\.(png|jpe?g|gif|webp)$/i.test(f));

const items = {};
// 1) auto folders
for (const c of fs.readdirSync(DIR)) {
  if (EXCLUDE.has(c)) continue;
  let stat; try { stat = fs.statSync(`${DIR}/${c}`); } catch { continue; }
  if (!stat.isDirectory()) continue;
  const files = imgs(`${DIR}/${c}`);
  if (files.length) items[c] = files.map((f) => ({ file: f, answer: clean(f) }));
}
// 2) the two letter categories, sharing letters/
const letterFiles = imgs(`${DIR}/letters`);
items.alphabet = letterFiles.map((f) => ({ file: f, answer: clean(f), imgDir: 'letters' }));
items.priorAlphabet = letterFiles
  .map((f) => ({ file: f, letter: clean(f) }))
  .filter((x) => /^[B-Z]$/.test(x.letter))                       // 'A' has no prior
  .map((x) => ({ file: x.file, answer: String.fromCharCode(x.letter.charCodeAt(0) - 1), shown: x.letter, imgDir: 'letters' }));

// order: put the alphabet pair first, then the rest
const order = ['alphabet', 'priorAlphabet', ...Object.keys(items).filter((k) => k !== 'alphabet' && k !== 'priorAlphabet')];
const categories = order.filter((k) => items[k]?.length).map((k) => ({
  key: k, en: LABELS[k]?.en || k, te: LABELS[k]?.te || k, count: items[k].length,
  ...(items[k][0].imgDir ? { imgDir: items[k][0].imgDir } : {}),
}));
const ordered = {}; for (const k of order) if (items[k]) ordered[k] = items[k];

fs.writeFileSync('public/rapid/items.js',
  '// Auto-generated by scripts/gen-rapid-items.mjs. Each item: { file, answer, [shown], [imgDir] }.\n' +
  'window.RAPID_CATEGORIES = ' + JSON.stringify(categories, null, 2) + ';\n' +
  'window.RAPID_ITEMS = ' + JSON.stringify(ordered, null, 2) + ';\n');
console.log('categories:', categories.map((c) => `${c.en}(${c.count})`).join(', '));
console.log('priorAlphabet sample:', items.priorAlphabet.slice(0, 3).map((i) => `${i.shown}→${i.answer}`).join(', '));
